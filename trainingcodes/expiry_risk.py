def classify_expiry_risk(row):

    score = row["expiry_risk_score"]

    days = row["days_to_expiry"]

    remaining = row["expected_remaining_stock"]

    # Already expired
    if days < 0:
        return "CRITICAL"

    # Very close to expiry and stock remains
    if days <= 30 and remaining > 0:
        return "CRITICAL"

    # High risk
    if score >= 0.75:
        return "HIGH"

    # Watch
    if score >= 0.45:
        return "WATCH"

    # Otherwise
    return "LOW"


