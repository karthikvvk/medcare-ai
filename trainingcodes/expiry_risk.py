def calculate_expiry_urgency(days):

    if days < 0:
        return 1.00

    elif days <= 7:
        return 1.00

    elif days <= 14:
        return 0.95

    elif days <= 30:
        return 0.85

    elif days <= 60:
        return 0.70

    elif days <= 90:
        return 0.50

    elif days <= 180:
        return 0.30

    elif days <= 365:
        return 0.15

    else:
        return 0.05


